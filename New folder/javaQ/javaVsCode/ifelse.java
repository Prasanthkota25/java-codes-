import java.util.Scanner;

public class ifelse {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter the number :");
        int n = sc.nextInt();

        if (n > 10) {
            System.out.println("hi Hello ");
        } else {
            System.out.println("bye");
        }

    }
}
